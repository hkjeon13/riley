// FlashInfer masks logits and seeds the running maximum with a finite
// -math::inf (-5e4) in raw QK units, so a real logit beyond that range is
// taken for a masked one. Qwen2.5-7B's last layer reaches |QK| ~ 1.05e5 and
// its attention output was then about 50 % off. The variant divides each raw
// logit by 2^4 before the mask and multiplies the exponent scale by 2^4. Both
// factors are exact powers of two, so s * sm_scale_log2 (and the running
// maximum) are bit-identical to the default variant for every logit the
// default handled correctly, and the usable range grows to |QK| < 8e5.
constexpr float kLogitRangeShift = 16.0F;

using DefaultVariant = flashinfer::DefaultAttention</*use_custom_mask=*/false,
                                                    /*use_sliding_window=*/false,
                                                    /*use_logits_soft_cap=*/false,
                                                    /*use_alibi=*/false>;

struct Variant : DefaultVariant {
  template <typename Params>
  __device__ __host__ Variant(const Params& params, uint32_t batch_idx, uint8_t* smem_ptr)
      : DefaultVariant(params, batch_idx, smem_ptr) {
    sm_scale_log2 *= kLogitRangeShift;
  }

  REGISTER_LOGITS_TRANSFORM(params, logits, batch_idx, qo_idx, kv_idx, qo_head_idx, kv_head_idx,
                            { return logits * (1.0F / kLogitRangeShift); })
};

// Fixed KV chunk in tokens (a multiple of the page size), or 0 for no KV
// split, from RILEY_NATIVE_FLASHINFER_KV_CHUNK. A row's chunks start at
// absolute positions 0, C, 2C, ... of its own context, and the merge folds
// them in order, so the split does not depend on the batch either.
// riley_cuda_set_native_flashinfer_kv_chunk overrides it.
std::atomic<uint64_t>& kv_chunk_setting() {
  static std::atomic<uint64_t> value{[] {
    const char* text = std::getenv("RILEY_NATIVE_FLASHINFER_KV_CHUNK");
    return text == nullptr ? 0ULL : std::strtoull(text, nullptr, 10);
  }()};
  return value;
}

// 1 launches one CTA per possible work item through FlashInfer's own launcher,
// the reference for strided_paged_kernel; see
// riley_cuda_set_native_flashinfer_full_grid.
std::atomic<uint32_t>& full_grid_setting() {
  static std::atomic<uint32_t> value{0};
  return value;
}

// A chunk that holds `page_capacity` pages cannot split any row, and a row in
// one chunk has the same bytes without the partial states and the merge.
uint32_t kv_chunk_tokens(uint64_t page_capacity) {
  const uint64_t chunk = kv_chunk_setting().load(std::memory_order_relaxed);
  return chunk % kPage == 0 && chunk <= (1ULL << 20) && chunk < page_capacity * kPage
             ? static_cast<uint32_t>(chunk)
             : 0U;
}

// Chunks of the longest context `page_capacity` pages can hold.
uint64_t max_chunks(uint64_t page_capacity, uint32_t chunk) {
  return chunk == 0 ? 1 : (page_capacity * kPage + chunk - 1) / chunk;
}

// Upper bound of work items (64-row tiles, times the KV chunks) for `rows`
// rows in any number of requests: each request adds at most one partial tile.
uint64_t max_work_items(uint64_t rows, uint64_t page_capacity,
                        uint32_t group_heads, uint32_t chunk) {
  return ((rows * group_heads + kCtaTileQ - 1) / kCtaTileQ + rows) *
         max_chunks(page_capacity, chunk);
}

struct Layout {
  uint64_t q_indptr, kv_indptr, last_page_len, o_indptr, kv_indices;
  uint64_t request_indices, qo_tile_indices, kv_tile_indices;
  uint64_t kv_chunk_size, total_rows, work_count, block_valid, merge_indptr, tmp_v, tmp_s;
  uint64_t bytes;
};

uint64_t align16(uint64_t value) { return (value + 15) & ~uint64_t{15}; }

// The chunk partial outputs (BF16) and log-sum-exps take one row per row and
// chunk; without a KV split they are absent.
Layout layout_for(uint64_t rows, uint64_t page_capacity, uint32_t query_heads,
                  uint32_t group_heads, uint32_t head_size, uint32_t chunk) {
  const uint64_t work = max_work_items(rows, page_capacity, group_heads, chunk);
  const uint64_t partial_rows = chunk == 0 ? 0 : rows * max_chunks(page_capacity, chunk);
  Layout layout{};
  uint64_t offset = 0;
  const auto take = [&](uint64_t bytes) {
    const uint64_t at = offset;
    offset = align16(offset + bytes);
    return at;
  };
  layout.q_indptr = take(4 * (rows + 1));
  layout.kv_indptr = take(4 * (rows + 1));
  layout.last_page_len = take(4 * rows);
  layout.o_indptr = take(4 * (rows + 1));
  layout.kv_indices = take(4 * rows * page_capacity);
  layout.request_indices = take(4 * work);
  layout.qo_tile_indices = take(4 * work);
  layout.kv_tile_indices = take(4 * work);
  layout.kv_chunk_size = take(4);
  layout.total_rows = take(4);
  layout.work_count = take(4);
  layout.block_valid = take(work);
  layout.merge_indptr = take(chunk == 0 ? 0 : 4 * (rows + 1));
  layout.tmp_v = take(partial_rows * query_heads * head_size * 2);
  layout.tmp_s = take(partial_rows * query_heads * 4);
  layout.bytes = offset;
  return layout;
}

// Exclusive block-wide sum of one value per thread; `*total` receives the
// sum. Uses `scratch[32]` shared words.
__device__ uint32_t block_exclusive_sum(uint32_t value, uint32_t* scratch,
                                        uint32_t* total) {
  const uint32_t lane = threadIdx.x % 32;
  const uint32_t warp = threadIdx.x / 32;
  uint32_t inclusive = value;
#pragma unroll
  for (uint32_t offset = 1; offset < 32; offset *= 2) {
    const uint32_t other = __shfl_up_sync(0xffffffffU, inclusive, offset);
    if (lane >= offset) {
      inclusive += other;
    }
  }
  if (lane == 31) {
    scratch[warp] = inclusive;
  }
  __syncthreads();
  if (warp == 0) {
    const uint32_t warps = blockDim.x / 32;
    uint32_t sum = lane < warps ? scratch[lane] : 0U;
#pragma unroll
    for (uint32_t offset = 1; offset < 32; offset *= 2) {
      const uint32_t other = __shfl_up_sync(0xffffffffU, sum, offset);
      if (lane >= offset) {
        sum += other;
      }
    }
    if (lane < warps) {
      scratch[lane] = sum;
    }
  }
  __syncthreads();
  const uint32_t warp_prefix = warp == 0 ? 0U : scratch[warp - 1];
  const uint32_t result = warp_prefix + inclusive - value;
  if (total != nullptr) {
    *total = scratch[blockDim.x / 32 - 1];
  }
  __syncthreads();
  return result;
}

// One CTA turns the rows into requests (runs of consecutive positions of one
// sequence), resolves each request's pages and writes FlashInfer's lists:
// q/kv/o indptr, page indices, last page lengths and one work item per
// 64-row packed query tile and KV chunk (`chunk` tokens, or the whole context
// when 0); with chunks also the merge lists over the partial rows. Unused work
// items are masked off. Rows past the active count are zeroed; rows of a
// request with an unresolvable page get NaN outputs and no work (with chunks,
// one NaN partial row each, which the merge copies).
__global__ __launch_bounds__(kPlannerThreads) void plan_kernel(
    RowBatch batch, uint64_t output_rows, uint64_t page_capacity,
    uint32_t group_heads, uint32_t row_width, uint32_t work_capacity,
    uint32_t chunk, IdType* q_indptr, IdType* kv_indptr, IdType* last_page_len,
    IdType* o_indptr, IdType* kv_indices, IdType* request_indices,
    IdType* qo_tile_indices, IdType* kv_tile_indices, IdType* kv_chunk_size,
    uint32_t* total_rows, uint32_t* work_count, bool* block_valid, IdType* merge_indptr,
    __nv_bfloat16* partial_output, __nv_bfloat16* output) {
  __shared__ uint32_t scratch[32];
  __shared__ uint8_t request_valid[kPlannerThreads];
  __shared__ uint32_t any_invalid;
  const uint32_t thread = threadIdx.x;
  uint64_t active = batch.dynamic_counts != nullptr
                        ? static_cast<uint64_t>(batch.dynamic_counts[0])
                        : batch.active_row_count;
  if (active > output_rows) {
    active = output_rows;
  }
  if (thread == 0) {
    any_invalid = 0;
  }
  const bool live = thread < active;
  const uint32_t slot = live ? batch.row_sequence_slots[thread] : 0U;
  const uint32_t position = live ? batch.row_positions[thread] : 0U;
  const bool start =
      live && (thread == 0 || batch.row_sequence_slots[thread - 1] != slot ||
               batch.row_positions[thread - 1] + 1 != position);
  uint32_t requests = 0;
  const uint32_t request_before = block_exclusive_sum(start ? 1U : 0U, scratch, &requests);
  const uint32_t row_request = request_before + (start ? 1U : 0U) - 1U;
  if (start) {
    q_indptr[request_before] = static_cast<IdType>(thread);
  }
  if (thread == 0) {
    q_indptr[requests] = static_cast<IdType>(active);
  }
  __syncthreads();

  // Thread r < requests owns request r.
  const bool owner = thread < requests;
  uint32_t pages = 0;
  uint32_t tiles = 0;
  uint32_t chunks = 1;
  uint32_t kv_length = 0;
  uint32_t first_row = 0;
  uint32_t end_row = 0;
  uint64_t block_begin = 0;
  bool valid = false;
  if (owner) {
    first_row = static_cast<uint32_t>(q_indptr[thread]);
    end_row = static_cast<uint32_t>(q_indptr[thread + 1]);
    kv_length = batch.row_positions[end_row - 1] + 1;
    pages = (kv_length + kPage - 1) / kPage;
    tiles = ((end_row - first_row) * group_heads + kCtaTileQ - 1) / kCtaTileQ;
    const uint64_t sequence = batch.row_sequence_slots[first_row];
    valid = sequence < batch.sequence_count && pages <= page_capacity;
    if (valid) {
      block_begin = batch.sequence_block_offsets[sequence];
      const uint64_t block_end = batch.sequence_block_offsets[sequence + 1];
      valid = block_begin <= block_end && block_end <= batch.block_count &&
              pages <= block_end - block_begin;
    }
    for (uint32_t page = 0; valid && page < pages; ++page) {
      const uint64_t index = block_begin + page;
      const uint32_t required =
          kv_length - page * kPage < kPage ? kv_length - page * kPage : kPage;
      const uint32_t physical = batch.block_ids[index];
      const uint32_t tokens = batch.valid_tokens[index];
      valid = physical < batch.physical_block_count && tokens >= required &&
              tokens != 0 && tokens <= kPage;
    }
    if (valid && chunk != 0) {
      chunks = (kv_length + chunk - 1) / chunk;
    }
    request_valid[thread] = valid ? 1 : 0;
    if (!valid) {
      atomicOr(&any_invalid, 1U);
    }
  }
  uint32_t total_pages = 0;
  const uint32_t page_before =
      block_exclusive_sum(valid ? pages : 0U, scratch, &total_pages);
  uint32_t total_tiles = 0;
  const uint32_t tile_before =
      block_exclusive_sum(valid ? tiles * chunks : 0U, scratch, &total_tiles);
  // Partial rows: one per row and chunk (one per row of an invalid request).
  uint32_t total_partial = 0;
  const uint32_t partial_before = block_exclusive_sum(
      owner && chunk != 0 ? (end_row - first_row) * chunks : 0U, scratch,
      &total_partial);
  if (owner) {
    kv_indptr[thread] = static_cast<IdType>(page_before);
    o_indptr[thread] = chunk != 0 ? static_cast<IdType>(partial_before) : q_indptr[thread];
    if (chunk != 0) {
      for (uint32_t row = first_row; row < end_row; ++row) {
        merge_indptr[row] =
            static_cast<IdType>(partial_before + (row - first_row) * chunks);
      }
    }
    last_page_len[thread] =
        valid ? static_cast<IdType>(kv_length - (pages - 1) * kPage) : 1;
    if (valid) {
      for (uint32_t page = 0; page < pages; ++page) {
        kv_indices[page_before + page] =
            static_cast<IdType>(batch.block_ids[block_begin + page]);
      }
      for (uint32_t tile = 0; tile < tiles; ++tile) {
        for (uint32_t part = 0; part < chunks; ++part) {
          const uint32_t item = tile_before + tile * chunks + part;
          request_indices[item] = static_cast<IdType>(thread);
          qo_tile_indices[item] = static_cast<IdType>(tile);
          kv_tile_indices[item] = static_cast<IdType>(part);
          block_valid[item] = true;
        }
      }
    }
  }
  // FlashInfer bounds page reads by `kv_indptr[batch_size]`, and the batch
  // size it is given is the row capacity: the lists past the last request
  // repeat the totals, so they describe empty requests.
  for (uint64_t entry = requests + thread; entry <= output_rows;
       entry += blockDim.x) {
    q_indptr[entry] = static_cast<IdType>(active);
    kv_indptr[entry] = static_cast<IdType>(total_pages);
    o_indptr[entry] =
        static_cast<IdType>(chunk != 0 ? total_partial : static_cast<uint32_t>(active));
    if (entry < output_rows) {
      last_page_len[entry] = 0;
    }
  }
  if (chunk != 0) {
    for (uint64_t entry = active + thread; entry <= output_rows; entry += blockDim.x) {
      merge_indptr[entry] = static_cast<IdType>(total_partial);
    }
  }
  if (thread == 0) {
    kv_chunk_size[0] = chunk != 0 ? static_cast<IdType>(chunk) : 1 << 30;
    total_rows[0] = static_cast<uint32_t>(active);
    work_count[0] = total_tiles;
  }
  for (uint32_t item = total_tiles + thread; item < work_capacity;
       item += blockDim.x) {
    request_indices[item] = 0;
    qo_tile_indices[item] = 0;
    kv_tile_indices[item] = 0;
    block_valid[item] = false;
  }
  __syncthreads();

  // Rows past the active count are zeros, as on the two-stage path.
  const uint64_t pad_vectors = (output_rows - active) * row_width / 8;
  uint4* const pad = reinterpret_cast<uint4*>(output + active * row_width);
  for (uint64_t index = thread; index < pad_vectors; index += blockDim.x) {
    pad[index] = make_uint4(0U, 0U, 0U, 0U);
  }
  if (any_invalid != 0) {
    const __nv_bfloat16 nan = __float2bfloat16_rn(CUDART_NAN_F);
    for (uint64_t index = thread; index < active * row_width; index += blockDim.x) {
      const uint64_t row = index / row_width;
      // The request of `row`: the last request starting at or before it.
      uint32_t low = 0;
      uint32_t high = requests;
      while (high - low > 1) {
        const uint32_t middle = (low + high) / 2;
        if (static_cast<uint64_t>(q_indptr[middle]) <= row) {
          low = middle;
        } else {
          high = middle;
        }
      }
      if (request_valid[low] == 0) {
        if (chunk != 0) {
          partial_output[static_cast<uint64_t>(merge_indptr[row]) * row_width +
                         index % row_width] = nan;
        } else {
          output[index] = nan;
        }
      }
    }
  }
  (void)row_request;
}

// FlashInfer's paged-prefill work items with `gridDim.x` CTAs striding over
// the planned count. Each item runs FlashInfer's device function with the
// same arguments as its own CTA would, so the bytes do not depend on the
// grid. One CTA per possible item (the bound for the longest context, with
// chunks) mostly ran empty CTAs: 9,088 for 256 Qwen2.5-7B rows at 8,192
// tokens, about 30 us per layer.
template <typename KTraits>
__global__ __launch_bounds__(KTraits::NUM_THREADS) void strided_paged_kernel(
    const __grid_constant__ PagedParams params) {
  extern __shared__ uint8_t smem[];
  auto& storage = reinterpret_cast<typename KTraits::SharedStoragePaged&>(smem);
  const uint32_t items = *params.work_count;
  for (uint32_t item = blockIdx.x; item < items; item += gridDim.x) {
    flashinfer::BatchPrefillWithPagedKVCacheDevice<KTraits>(
        params, storage, threadIdx, item, blockIdx.z, gridDim.z);
    __syncthreads();
  }
}

constexpr uint32_t kMergeVector = 8;
constexpr uint32_t kMergeThreads = 256;

// FlashInfer's VariableLengthMergeStates with one thread per 8 values of a row
// and head instead of one 128-thread CTA per row and head. In FlashInfer's CTA
// thread slot y folds parts y, y + slots, ... and the CTA then folds the
// slots' BF16-staged results in slot order; this replays both folds with the
// same state_t operations, so the bytes are the same. FlashInfer's persistent
// CTAs took 37 us for 256 Qwen2.5-7B rows of two parts and 8 us to copy rows
// of one part.
template <uint32_t kHead>
__global__ __launch_bounds__(kMergeThreads) void merge_parts_kernel(
    const DTypeO* parts, const float* lse, const IdType* indptr, DTypeO* output,
    const uint32_t* rows, uint32_t heads) {
  constexpr uint32_t kLanes = kHead / kMergeVector;
  constexpr uint32_t kSlots = 128 / kLanes;
  const uint64_t index = static_cast<uint64_t>(blockIdx.x) * blockDim.x + threadIdx.x;
  const uint64_t pair = index / kLanes;
  if (pair >= static_cast<uint64_t>(*rows) * heads) {
    return;
  }
  const uint32_t lane = static_cast<uint32_t>(index % kLanes);
  const uint32_t row = static_cast<uint32_t>(pair / heads);
  const uint32_t head = static_cast<uint32_t>(pair % heads);
  const uint32_t first = static_cast<uint32_t>(indptr[row]);
  const uint32_t count = static_cast<uint32_t>(indptr[row + 1]) - first;
  DTypeO* const out = output + pair * kHead + lane * kMergeVector;
  const auto part_values = [&](uint32_t part) {
    return parts + (static_cast<uint64_t>(first + part) * heads + head) * kHead +
           lane * kMergeVector;
  };
  if (count == 0) {
    flashinfer::vec_t<DTypeO, kMergeVector> zeros;
    zeros.fill(DTypeO(0.F));
    zeros.store(out);
    return;
  }
  if (count == 1) {
    flashinfer::vec_t<DTypeO, kMergeVector> copy;
    copy.cast_load(part_values(0));
    copy.store(out);
    return;
  }
  flashinfer::state_t<kMergeVector> total;
  for (uint32_t slot = 0; slot < kSlots; ++slot) {
    flashinfer::state_t<kMergeVector> state;
    for (uint32_t part = slot; part < count; part += kSlots) {
      flashinfer::vec_t<float, kMergeVector> values;
      values.cast_load(part_values(part));
      state.merge(values, lse[static_cast<uint64_t>(first + part) * heads + head], 1);
    }
    state.normalize();
    alignas(16) DTypeO staged[kMergeVector];
    state.o.cast_store(staged);
    flashinfer::vec_t<float, kMergeVector> values;
    values.cast_load(staged);
    total.merge(values, state.get_lse(), 1);
  }
  total.normalize();
  total.o.cast_store(out);
}

// BatchPrefillWithPagedKVCacheDispatched with strided_paged_kernel: the same
// KernelTraits choice (FlashInfer 0.6.16's rule for BF16, no position encoding
// and equal head sizes up to 256), on a grid of at most the resident CTAs,
// then merge_parts_kernel.
template <uint32_t kHead>
cudaError_t launch_strided(PagedParams params, DTypeO* tmp_v, float* tmp_s,
                           uint32_t work_capacity, cudaStream_t stream) {
  static_assert(kHead / 16 <= 16, "the KV tile rule below assumes no VO split");
  constexpr uint32_t kNumMmaQ = flashinfer::get_num_mma_q(kCtaTileQ);
  constexpr uint32_t kWarpsQ = flashinfer::get_num_warps_q(kCtaTileQ);
  constexpr uint32_t kWarpsKv = flashinfer::get_num_warps_kv(kCtaTileQ);
  constexpr uint32_t kSmemPerMmaKv = 2 * kHead * 16 * kWarpsKv * sizeof(DTypeKV);
  constexpr uint32_t kFixedSmem = kCtaTileQ * kHead * sizeof(DTypeQ);
  int device = 0;
  int sms = 0;
  int smem_per_sm = 0;
  int smem_per_block = 0;
  cudaError_t status = cudaGetDevice(&device);
  if (status == cudaSuccess) {
    status = cudaDeviceGetAttribute(&sms, cudaDevAttrMultiProcessorCount, device);
  }
  if (status == cudaSuccess) {
    status = cudaDeviceGetAttribute(&smem_per_sm,
                                    cudaDevAttrMaxSharedMemoryPerMultiprocessor, device);
  }
  if (status == cudaSuccess) {
    status = cudaDeviceGetAttribute(&smem_per_block,
                                    cudaDevAttrMaxSharedMemoryPerBlockOptin, device);
  }
  if (status != cudaSuccess) {
    return status;
  }
  const int ctas_per_sm =
      smem_per_sm >= static_cast<int>(2 * (kFixedSmem + kSmemPerMmaKv)) ? 2 : 1;
  const int smem_per_cta = min(smem_per_sm / ctas_per_sm, smem_per_block);
  const int mma_kv_smem = (smem_per_cta - static_cast<int>(kFixedSmem)) /
                          static_cast<int>(kSmemPerMmaKv);
  if (mma_kv_smem < 1) {
    return cudaErrorNotSupported;
  }
  const uint32_t num_kv_heads = params.paged_kv.num_heads;
  const uint32_t resident = static_cast<uint32_t>(sms * ctas_per_sm);
  const dim3 blocks(work_capacity < resident ? work_capacity : resident, 1, num_kv_heads);
  const dim3 threads(32, kWarpsQ, kWarpsKv);
  DISPATCH_NUM_MMA_KV(min(static_cast<uint32_t>(mma_kv_smem), 8U / kNumMmaQ), kNumMmaKv, {
    using KTraits = flashinfer::KernelTraits<
        flashinfer::MaskMode::kCausal, kCtaTileQ, kNumMmaQ, kNumMmaKv, kHead / 16,
        kHead / 16, kWarpsQ, kWarpsKv, flashinfer::PosEncodingMode::kNone, DTypeQ,
        DTypeKV, DTypeO, float, IdType, Variant>;
    if constexpr (KTraits::IsInvalid()) {
      return cudaErrorNotSupported;
    } else {
      const size_t smem = sizeof(typename KTraits::SharedStoragePaged);
      if (smem > static_cast<size_t>(smem_per_block)) {
        return cudaErrorNotSupported;
      }
      auto* kernel = strided_paged_kernel<KTraits>;
      status = cudaFuncSetAttribute(kernel, cudaFuncAttributeMaxDynamicSharedMemorySize,
                                    static_cast<int>(smem));
      if (status != cudaSuccess) {
        return status;
      }
      DTypeO* const output = params.o;
      params.partition_kv = tmp_v != nullptr;
      if (tmp_v != nullptr) {
        params.o = tmp_v;
        params.lse = tmp_s;
      }
      kernel<<<blocks, threads, smem, stream>>>(params);
      status = cudaGetLastError();
      if (status != cudaSuccess || tmp_v == nullptr) {
        return status;
      }
      const uint64_t merge_threads = static_cast<uint64_t>(params.max_total_num_rows) *
                                     params.num_qo_heads * (kHead / kMergeVector);
      merge_parts_kernel<kHead>
          <<<static_cast<uint32_t>((merge_threads + kMergeThreads - 1) / kMergeThreads),
             kMergeThreads, 0, stream>>>(tmp_v, tmp_s, params.merge_indptr, output,
                                         params.total_num_rows, params.num_qo_heads);
      return cudaGetLastError();
    }
  });
  return cudaErrorNotSupported;
}

}  // namespace

uint64_t workspace_bytes(uint64_t output_rows, uint64_t page_capacity,
                         uint32_t query_heads, uint32_t key_value_heads,
                         uint32_t head_size) {
  if (key_value_heads == 0 || query_heads % key_value_heads != 0) {
    return UINT64_MAX;
  }
  return layout_for(output_rows, page_capacity, query_heads,
                    query_heads / key_value_heads, head_size,
                    kv_chunk_tokens(page_capacity))
      .bytes;
}

template <uint32_t kHead>
cudaError_t run_paged_attention(const __nv_bfloat16* query,
                                const __nv_bfloat16* key_pool,
                                const __nv_bfloat16* value_pool,
                                __nv_bfloat16* output, const RowBatch& batch,
                                uint64_t output_rows, uint64_t page_capacity,
                                uint32_t query_heads, uint32_t key_value_heads,
                                float scale, void* workspace,
                                uint64_t workspace_size, bool plan,
                                cudaStream_t stream) {
  if (output_rows == 0 || output_rows > kPlannerThreads || key_value_heads == 0 ||
      query_heads % key_value_heads != 0) {
    return cudaErrorInvalidValue;
  }
  const uint32_t group_heads = query_heads / key_value_heads;
  const uint32_t chunk = kv_chunk_tokens(page_capacity);
  const Layout layout =
      layout_for(output_rows, page_capacity, query_heads, group_heads, kHead, chunk);
  if (workspace == nullptr || workspace_size < layout.bytes) {
    return cudaErrorInvalidValue;
  }
  auto* base = static_cast<uint8_t*>(workspace);
  const auto ids = [&](uint64_t offset) { return reinterpret_cast<IdType*>(base + offset); };
  const uint32_t work = static_cast<uint32_t>(
      max_work_items(output_rows, page_capacity, group_heads, chunk));
  const uint32_t row_width = query_heads * kHead;
  if (plan) {
  plan_kernel<<<1, kPlannerThreads, 0, stream>>>(
      batch, output_rows, page_capacity, group_heads, row_width, work, chunk,
      ids(layout.q_indptr), ids(layout.kv_indptr), ids(layout.last_page_len),
      ids(layout.o_indptr), ids(layout.kv_indices), ids(layout.request_indices),
      ids(layout.qo_tile_indices), ids(layout.kv_tile_indices),
      ids(layout.kv_chunk_size),
      reinterpret_cast<uint32_t*>(base + layout.total_rows),
      reinterpret_cast<uint32_t*>(base + layout.work_count),
      reinterpret_cast<bool*>(base + layout.block_valid), ids(layout.merge_indptr),
      reinterpret_cast<__nv_bfloat16*>(base + layout.tmp_v), output);
  const cudaError_t status = cudaGetLastError();
  if (status != cudaSuccess) {
    return status;
  }
  }

  PagedParams params{};
  params.q = const_cast<DTypeQ*>(query);
  params.paged_kv = flashinfer::paged_kv_t<DTypeKV, IdType>(
      key_value_heads, kPage, kHead, static_cast<uint32_t>(output_rows),
      flashinfer::QKVLayout::kHND, const_cast<DTypeKV*>(key_pool),
      const_cast<DTypeKV*>(value_pool), ids(layout.kv_indices),
      ids(layout.kv_indptr), ids(layout.last_page_len));
  params.q_indptr = ids(layout.q_indptr);
  params.o = output;
  params.lse = nullptr;
  params.group_size = flashinfer::uint_fastdiv(group_heads);
  params.logits_soft_cap = 0.0;
  params.sm_scale = scale;
  params.rope_rcp_scale = 1.0;
  params.rope_rcp_theta = 1.0;
  params.num_qo_heads = query_heads;
  params.q_stride_n = static_cast<IdType>(row_width);
  params.q_stride_h = static_cast<IdType>(kHead);
  params.window_left = -1;
  params.request_indices = ids(layout.request_indices);
  params.qo_tile_indices = ids(layout.qo_tile_indices);
  params.kv_tile_indices = ids(layout.kv_tile_indices);
  params.merge_indptr = chunk != 0 ? ids(layout.merge_indptr) : nullptr;
  params.o_indptr = ids(layout.o_indptr);
  params.block_valid_mask = reinterpret_cast<bool*>(base + layout.block_valid);
  params.kv_chunk_size_ptr = ids(layout.kv_chunk_size);
  params.max_total_num_rows = static_cast<uint32_t>(output_rows);
  params.total_num_rows = reinterpret_cast<uint32_t*>(base + layout.total_rows);
  params.padded_batch_size = work;
  params.partition_kv = false;
  params.work_count = reinterpret_cast<const uint32_t*>(base + layout.work_count);
  DTypeO* const tmp_v = chunk != 0 ? reinterpret_cast<DTypeO*>(base + layout.tmp_v) : nullptr;
  float* const tmp_s = chunk != 0 ? reinterpret_cast<float*>(base + layout.tmp_s) : nullptr;
  if (full_grid_setting().load(std::memory_order_relaxed) == 0) {
    return launch_strided<kHead>(params, tmp_v, tmp_s, work, stream);
  }
  try {
    return flashinfer::BatchPrefillWithPagedKVCacheDispatched<
        kCtaTileQ, kHead, kHead, flashinfer::PosEncodingMode::kNone,
        /*USE_FP16_QK_REDUCTION=*/false, flashinfer::MaskMode::kCausal, Variant,
        PagedParams>(params, tmp_v, tmp_s, /*enable_pdl=*/false, stream);
  } catch (...) {
    // FlashInfer rejects an unsupported configuration with an exception.
    return cudaErrorNotSupported;
  }
}

cudaError_t paged_attention(const __nv_bfloat16* query,
                            const __nv_bfloat16* key_pool,
                            const __nv_bfloat16* value_pool,
                            __nv_bfloat16* output, const RowBatch& batch,
                            uint64_t output_rows, uint64_t page_capacity,
                            uint32_t query_heads, uint32_t key_value_heads,
                            uint32_t head_size, float scale, void* workspace,
                            uint64_t workspace_size, bool plan,
                            cudaStream_t stream) {
  switch (head_size) {
    case 64:
      return run_paged_attention<64>(query, key_pool, value_pool, output, batch,
                                     output_rows, page_capacity, query_heads,
                                     key_value_heads, scale, workspace,
                                     workspace_size, plan, stream);
    case 128:
      return run_paged_attention<128>(query, key_pool, value_pool, output, batch,
                                      output_rows, page_capacity, query_heads,
                                      key_value_heads, scale, workspace,
                                      workspace_size, plan, stream);
    default:
      return cudaErrorInvalidValue;
  }
}

