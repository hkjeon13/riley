using DTypeQ = nv_bfloat16;
using DTypeKV = nv_bfloat16;
using DTypeO = nv_bfloat16;
using IdType = int32_t;

constexpr uint32_t kPage = 16;
// The fixed query tile: rows x query heads of one KV head are packed into
// 64-row tiles, and the warp layout (4 query warps, 1 KV warp) and KV tile
// follow from it, so every row's KV fold has the same structure in every
// batch.
constexpr uint32_t kCtaTileQ = 64;
constexpr uint32_t kPlannerThreads = 1024;

// FlashInfer's paged-prefill parameters for BF16, no position encoding, as
// generated by FlashInfer 0.6.16.post3's JIT for that config (the same struct
// for every head dimension).
struct PagedParams {
  using DTypeQ = riley_fi::DTypeQ;
  using DTypeKV = riley_fi::DTypeKV;
  using DTypeO = riley_fi::DTypeO;
  using IdType = riley_fi::IdType;

  DTypeQ* q;
  flashinfer::paged_kv_t<DTypeKV, IdType> paged_kv;
  IdType* q_indptr;
  DTypeO* o;
  float* lse;
  flashinfer::uint_fastdiv group_size;

  uint8_t* maybe_custom_mask;
  int32_t* maybe_mask_indptr;
  float* maybe_alibi_slopes;
  uint32_t* maybe_prefix_len_ptr;
  uint16_t* maybe_token_pos_in_items_ptr;
  uint16_t* maybe_max_item_len_ptr;
  uint8_t* maybe_k_cache_sf;
  uint8_t* maybe_v_cache_sf;
  double logits_soft_cap;
  double sm_scale;
  double rope_rcp_scale;
  double rope_rcp_theta;
  int64_t token_pos_in_items_len;

  uint32_t num_qo_heads;
  IdType q_stride_n;
  IdType q_stride_h;
  uint32_t k_sf_stride_page;
  uint32_t k_sf_stride_n;
  uint32_t k_sf_stride_h;
  uint32_t v_sf_stride_page;
  uint32_t v_sf_stride_n;
  uint32_t v_sf_stride_h;
  int32_t window_left;

  IdType* request_indices;
  IdType* qo_tile_indices;
  IdType* kv_tile_indices;
  IdType* merge_indptr;
  IdType* o_indptr;
  bool* block_valid_mask;
  IdType* kv_chunk_size_ptr;
  uint32_t max_total_num_rows;
  uint32_t* total_num_rows;
  uint32_t padded_batch_size;
  bool partition_kv;

  __host__ __device__ __forceinline__ uint32_t get_qo_len(uint32_t batch_idx) const {
    return q_indptr[batch_idx + 1] - q_indptr[batch_idx];
  }

  __host__ __device__ __forceinline__ uint32_t get_kv_len(uint32_t batch_idx) const {
    return paged_kv.get_length(batch_idx);
  }
};

using Variant = flashinfer::DefaultAttention</*use_custom_mask=*/false,
                                             /*use_sliding_window=*/false,
                                             /*use_logits_soft_cap=*/false,
                                             /*use_alibi=*/false>;

// Upper bound of work items (64-row tiles) for `rows` rows in any number of
// requests: each request adds at most one partial tile.
uint64_t max_work_items(uint64_t rows, uint32_t group_heads) {
  return (rows * group_heads + kCtaTileQ - 1) / kCtaTileQ + rows;
}

struct Layout {
  uint64_t q_indptr, kv_indptr, last_page_len, o_indptr, kv_indices;
  uint64_t request_indices, qo_tile_indices, kv_tile_indices;
  uint64_t kv_chunk_size, total_rows, block_valid, bytes;
};

uint64_t align16(uint64_t value) { return (value + 15) & ~uint64_t{15}; }

Layout layout_for(uint64_t rows, uint64_t page_capacity, uint32_t group_heads) {
  const uint64_t work = max_work_items(rows, group_heads);
  Layout layout{};
  uint64_t offset = 0;
  const auto take = [&](uint64_t bytes) {
    const uint64_t at = offset;
    offset = align16(offset + bytes);
    return at;
  };
  layout.q_indptr = take(4 * (rows + 1));
  layout.kv_indptr = take(4 * (rows + 1));
  layout.last_page_len = take(4 * rows);
  layout.o_indptr = take(4 * (rows + 1));
  layout.kv_indices = take(4 * rows * page_capacity);
  layout.request_indices = take(4 * work);
  layout.qo_tile_indices = take(4 * work);
  layout.kv_tile_indices = take(4 * work);
  layout.kv_chunk_size = take(4);
  layout.total_rows = take(4);
  layout.block_valid = take(work);
  layout.bytes = offset;
  return layout;
}

// Exclusive block-wide sum of one value per thread; `*total` receives the
// sum. Uses `scratch[32]` shared words.
__device__ uint32_t block_exclusive_sum(uint32_t value, uint32_t* scratch,
                                        uint32_t* total) {
  const uint32_t lane = threadIdx.x % 32;
  const uint32_t warp = threadIdx.x / 32;
  uint32_t inclusive = value;
#pragma unroll
  for (uint32_t offset = 1; offset < 32; offset *= 2) {
    const uint32_t other = __shfl_up_sync(0xffffffffU, inclusive, offset);
    if (lane >= offset) {
      inclusive += other;
    }
  }
  if (lane == 31) {
    scratch[warp] = inclusive;
  }
  __syncthreads();
  if (warp == 0) {
    const uint32_t warps = blockDim.x / 32;
    uint32_t sum = lane < warps ? scratch[lane] : 0U;
#pragma unroll
    for (uint32_t offset = 1; offset < 32; offset *= 2) {
      const uint32_t other = __shfl_up_sync(0xffffffffU, sum, offset);
      if (lane >= offset) {
        sum += other;
      }
    }
    if (lane < warps) {
      scratch[lane] = sum;
    }
  }
  __syncthreads();
  const uint32_t warp_prefix = warp == 0 ? 0U : scratch[warp - 1];
  const uint32_t result = warp_prefix + inclusive - value;
  if (total != nullptr) {
    *total = scratch[blockDim.x / 32 - 1];
  }
  __syncthreads();
  return result;
}

// One CTA turns the rows into requests (runs of consecutive positions of one
// sequence), resolves each request's pages and writes FlashInfer's lists:
// q/kv/o indptr, page indices, last page lengths and one work item per
// 64-row packed query tile (no KV split). Unused work items are masked off.
// Rows past the active count are zeroed; rows of a request with an
// unresolvable page get NaN outputs and no work.
__global__ __launch_bounds__(kPlannerThreads) void plan_kernel(
    RowBatch batch, uint64_t output_rows, uint64_t page_capacity,
    uint32_t group_heads, uint32_t row_width, uint32_t work_capacity,
    IdType* q_indptr, IdType* kv_indptr, IdType* last_page_len,
    IdType* o_indptr, IdType* kv_indices, IdType* request_indices,
    IdType* qo_tile_indices, IdType* kv_tile_indices, IdType* kv_chunk_size,
    uint32_t* total_rows, bool* block_valid, __nv_bfloat16* output) {
  __shared__ uint32_t scratch[32];
  __shared__ uint8_t request_valid[kPlannerThreads];
  __shared__ uint32_t any_invalid;
  const uint32_t thread = threadIdx.x;
  uint64_t active = batch.dynamic_counts != nullptr
                        ? static_cast<uint64_t>(batch.dynamic_counts[0])
                        : batch.active_row_count;
  if (active > output_rows) {
    active = output_rows;
  }
  if (thread == 0) {
    any_invalid = 0;
  }
  const bool live = thread < active;
  const uint32_t slot = live ? batch.row_sequence_slots[thread] : 0U;
  const uint32_t position = live ? batch.row_positions[thread] : 0U;
  const bool start =
      live && (thread == 0 || batch.row_sequence_slots[thread - 1] != slot ||
               batch.row_positions[thread - 1] + 1 != position);
  uint32_t requests = 0;
  const uint32_t request_before = block_exclusive_sum(start ? 1U : 0U, scratch, &requests);
  const uint32_t row_request = request_before + (start ? 1U : 0U) - 1U;
  if (start) {
    q_indptr[request_before] = static_cast<IdType>(thread);
  }
  if (thread == 0) {
    q_indptr[requests] = static_cast<IdType>(active);
  }
  __syncthreads();

  // Thread r < requests owns request r.
  const bool owner = thread < requests;
  uint32_t pages = 0;
  uint32_t tiles = 0;
  uint32_t kv_length = 0;
  uint64_t block_begin = 0;
  bool valid = false;
  if (owner) {
    const uint32_t first_row = static_cast<uint32_t>(q_indptr[thread]);
    const uint32_t end_row = static_cast<uint32_t>(q_indptr[thread + 1]);
    kv_length = batch.row_positions[end_row - 1] + 1;
    pages = (kv_length + kPage - 1) / kPage;
    tiles = ((end_row - first_row) * group_heads + kCtaTileQ - 1) / kCtaTileQ;
    const uint64_t sequence = batch.row_sequence_slots[first_row];
    valid = sequence < batch.sequence_count && pages <= page_capacity;
    if (valid) {
      block_begin = batch.sequence_block_offsets[sequence];
      const uint64_t block_end = batch.sequence_block_offsets[sequence + 1];
      valid = block_begin <= block_end && block_end <= batch.block_count &&
              pages <= block_end - block_begin;
    }
    for (uint32_t page = 0; valid && page < pages; ++page) {
      const uint64_t index = block_begin + page;
      const uint32_t required =
          kv_length - page * kPage < kPage ? kv_length - page * kPage : kPage;
      const uint32_t physical = batch.block_ids[index];
      const uint32_t tokens = batch.valid_tokens[index];
      valid = physical < batch.physical_block_count && tokens >= required &&
              tokens != 0 && tokens <= kPage;
    }
    request_valid[thread] = valid ? 1 : 0;
    if (!valid) {
      atomicOr(&any_invalid, 1U);
    }
  }
  uint32_t total_pages = 0;
  const uint32_t page_before =
      block_exclusive_sum(valid ? pages : 0U, scratch, &total_pages);
  uint32_t total_tiles = 0;
  const uint32_t tile_before =
      block_exclusive_sum(valid ? tiles : 0U, scratch, &total_tiles);
  if (owner) {
    kv_indptr[thread] = static_cast<IdType>(page_before);
    o_indptr[thread] = q_indptr[thread];
    last_page_len[thread] =
        valid ? static_cast<IdType>(kv_length - (pages - 1) * kPage) : 1;
    if (valid) {
      for (uint32_t page = 0; page < pages; ++page) {
        kv_indices[page_before + page] =
            static_cast<IdType>(batch.block_ids[block_begin + page]);
      }
      for (uint32_t tile = 0; tile < tiles; ++tile) {
        request_indices[tile_before + tile] = static_cast<IdType>(thread);
        qo_tile_indices[tile_before + tile] = static_cast<IdType>(tile);
        kv_tile_indices[tile_before + tile] = 0;
        block_valid[tile_before + tile] = true;
      }
    }
  }
  // FlashInfer bounds page reads by `kv_indptr[batch_size]`, and the batch
  // size it is given is the row capacity: the lists past the last request
  // repeat the totals, so they describe empty requests.
  for (uint64_t entry = requests + thread; entry <= output_rows;
       entry += blockDim.x) {
    q_indptr[entry] = static_cast<IdType>(active);
    kv_indptr[entry] = static_cast<IdType>(total_pages);
    o_indptr[entry] = static_cast<IdType>(active);
    if (entry < output_rows) {
      last_page_len[entry] = 0;
    }
  }
  if (thread == 0) {
    kv_chunk_size[0] = 1 << 30;
    total_rows[0] = static_cast<uint32_t>(active);
  }
  for (uint32_t item = total_tiles + thread; item < work_capacity;
       item += blockDim.x) {
    request_indices[item] = 0;
    qo_tile_indices[item] = 0;
    kv_tile_indices[item] = 0;
    block_valid[item] = false;
  }
  __syncthreads();

  // Rows past the active count are zeros, as on the two-stage path.
  const uint64_t pad_vectors = (output_rows - active) * row_width / 8;
  uint4* const pad = reinterpret_cast<uint4*>(output + active * row_width);
  for (uint64_t index = thread; index < pad_vectors; index += blockDim.x) {
    pad[index] = make_uint4(0U, 0U, 0U, 0U);
  }
  if (any_invalid != 0) {
    const __nv_bfloat16 nan = __float2bfloat16_rn(CUDART_NAN_F);
    for (uint64_t index = thread; index < active * row_width; index += blockDim.x) {
      const uint64_t row = index / row_width;
      // The request of `row`: the last request starting at or before it.
      uint32_t low = 0;
      uint32_t high = requests;
      while (high - low > 1) {
        const uint32_t middle = (low + high) / 2;
        if (static_cast<uint64_t>(q_indptr[middle]) <= row) {
          low = middle;
        } else {
          high = middle;
        }
      }
      if (request_valid[low] == 0) {
        output[index] = nan;
      }
    }
  }
  (void)row_request;
}

}  // namespace

uint64_t workspace_bytes(uint64_t output_rows, uint64_t page_capacity,
                         uint32_t group_heads) {
  return layout_for(output_rows, page_capacity, group_heads).bytes;
}

template <uint32_t kHead>
cudaError_t run_paged_attention(const __nv_bfloat16* query,
                                const __nv_bfloat16* key_pool,
                                const __nv_bfloat16* value_pool,
                                __nv_bfloat16* output, const RowBatch& batch,
                                uint64_t output_rows, uint64_t page_capacity,
                                uint32_t query_heads, uint32_t key_value_heads,
                                float scale, void* workspace,
                                uint64_t workspace_size, bool plan,
                                cudaStream_t stream) {
  if (output_rows == 0 || output_rows > kPlannerThreads || key_value_heads == 0 ||
      query_heads % key_value_heads != 0) {
    return cudaErrorInvalidValue;
  }
  const uint32_t group_heads = query_heads / key_value_heads;
  const Layout layout = layout_for(output_rows, page_capacity, group_heads);
  if (workspace == nullptr || workspace_size < layout.bytes) {
    return cudaErrorInvalidValue;
  }
  auto* base = static_cast<uint8_t*>(workspace);
  const auto ids = [&](uint64_t offset) { return reinterpret_cast<IdType*>(base + offset); };
  const uint32_t work = static_cast<uint32_t>(max_work_items(output_rows, group_heads));
  const uint32_t row_width = query_heads * kHead;
  if (plan) {
  plan_kernel<<<1, kPlannerThreads, 0, stream>>>(
      batch, output_rows, page_capacity, group_heads, row_width, work,
      ids(layout.q_indptr), ids(layout.kv_indptr), ids(layout.last_page_len),
      ids(layout.o_indptr), ids(layout.kv_indices), ids(layout.request_indices),
      ids(layout.qo_tile_indices), ids(layout.kv_tile_indices),
      ids(layout.kv_chunk_size),
      reinterpret_cast<uint32_t*>(base + layout.total_rows),
      reinterpret_cast<bool*>(base + layout.block_valid), output);
  const cudaError_t status = cudaGetLastError();
  if (status != cudaSuccess) {
    return status;
  }
  }

  PagedParams params{};
  params.q = const_cast<DTypeQ*>(query);
  params.paged_kv = flashinfer::paged_kv_t<DTypeKV, IdType>(
      key_value_heads, kPage, kHead, static_cast<uint32_t>(output_rows),
      flashinfer::QKVLayout::kHND, const_cast<DTypeKV*>(key_pool),
      const_cast<DTypeKV*>(value_pool), ids(layout.kv_indices),
      ids(layout.kv_indptr), ids(layout.last_page_len));
  params.q_indptr = ids(layout.q_indptr);
  params.o = output;
  params.lse = nullptr;
  params.group_size = flashinfer::uint_fastdiv(group_heads);
  params.logits_soft_cap = 0.0;
  params.sm_scale = scale;
  params.rope_rcp_scale = 1.0;
  params.rope_rcp_theta = 1.0;
  params.num_qo_heads = query_heads;
  params.q_stride_n = static_cast<IdType>(row_width);
  params.q_stride_h = static_cast<IdType>(kHead);
  params.window_left = -1;
  params.request_indices = ids(layout.request_indices);
  params.qo_tile_indices = ids(layout.qo_tile_indices);
  params.kv_tile_indices = ids(layout.kv_tile_indices);
  params.merge_indptr = nullptr;
  params.o_indptr = ids(layout.o_indptr);
  params.block_valid_mask = reinterpret_cast<bool*>(base + layout.block_valid);
  params.kv_chunk_size_ptr = ids(layout.kv_chunk_size);
  params.max_total_num_rows = static_cast<uint32_t>(output_rows);
  params.total_num_rows = reinterpret_cast<uint32_t*>(base + layout.total_rows);
  params.padded_batch_size = work;
  params.partition_kv = false;
  try {
    return flashinfer::BatchPrefillWithPagedKVCacheDispatched<
        kCtaTileQ, kHead, kHead, flashinfer::PosEncodingMode::kNone,
        /*USE_FP16_QK_REDUCTION=*/false, flashinfer::MaskMode::kCausal, Variant,
        PagedParams>(params, /*tmp_v=*/nullptr, /*tmp_s=*/nullptr,
                     /*enable_pdl=*/false, stream);
  } catch (...) {
    // FlashInfer rejects an unsupported configuration with an exception.
    return cudaErrorNotSupported;
  }
}

cudaError_t paged_attention(const __nv_bfloat16* query,
                            const __nv_bfloat16* key_pool,
                            const __nv_bfloat16* value_pool,
                            __nv_bfloat16* output, const RowBatch& batch,
                            uint64_t output_rows, uint64_t page_capacity,
                            uint32_t query_heads, uint32_t key_value_heads,
                            uint32_t head_size, float scale, void* workspace,
                            uint64_t workspace_size, bool plan,
                            cudaStream_t stream) {
  switch (head_size) {
    case 64:
      return run_paged_attention<64>(query, key_pool, value_pool, output, batch,
                                     output_rows, page_capacity, query_heads,
                                     key_value_heads, scale, workspace,
                                     workspace_size, plan, stream);
    case 128:
      return run_paged_attention<128>(query, key_pool, value_pool, output, batch,
                                      output_rows, page_capacity, query_heads,
                                      key_value_heads, scale, workspace,
                                      workspace_size, plan, stream);
    default:
      return cudaErrorInvalidValue;
  }
}

